"""Write src/model/palettes.ts from Matplotlib's colormaps, so the app's palettes are exactly Matplotlib's.

    python frontend/scripts/palettes.py      # needs matplotlib; the output is committed, so only rerun to change the list

Qualitative maps keep their own colours in order. Continuous maps are sampled evenly; most skip their
extreme ends, which are near white or near black and vanish against one of the two themes.
See https://matplotlib.org/stable/users/explain/colors/colormaps.html
"""

from pathlib import Path

import matplotlib
from matplotlib.colors import to_hex

N = 10  # samples from a continuous map

# (family, [(name, low, high)]): low/high bound the sampled range of continuous maps
FAMILIES = [
    ("Qualitative", ["tab10", "tab20", "Set1", "Set2", "Set3", "Dark2", "Paired", "Accent", "Pastel1", "Pastel2"]),
    ("Perceptually uniform", [("viridis", 0, 0.95), ("plasma", 0.05, 0.92), ("inferno", 0.15, 0.92), ("magma", 0.15, 0.92), ("cividis", 0, 0.95)]),
    ("Sequential", [("Blues", 0.3, 1), ("Greens", 0.3, 1), ("Oranges", 0.3, 1), ("Purples", 0.3, 1), ("Reds", 0.3, 1),
                    ("YlGnBu", 0.25, 1), ("YlOrRd", 0.25, 1), ("PuBuGn", 0.3, 1)]),
    ("Diverging", [("Spectral", 0, 1), ("coolwarm", 0, 1), ("RdYlBu", 0, 1), ("RdYlGn", 0, 1), ("PiYG", 0, 1), ("PRGn", 0, 1), ("BrBG", 0, 1)]),
    ("Cyclic", [("twilight", 0.05, 0.95), ("hsv", 0, 0.9)]),
    ("Miscellaneous", [("turbo", 0.05, 0.95), ("rainbow", 0, 1), ("terrain", 0, 0.8), ("cubehelix", 0.15, 0.85), ("ocean", 0.15, 0.95)]),
]


def colours(spec) -> list[str]:
    if isinstance(spec, str):
        cmap = matplotlib.colormaps[spec]
        return [to_hex(c) for c in cmap.colors]  # a ListedColormap: its own colours
    name, low, high = spec
    cmap = matplotlib.colormaps[name]
    return [to_hex(cmap(low + (high - low) * i / (N - 1))) for i in range(N)]


lines = [
    "/** Matplotlib colormaps, generated by scripts/palettes.py (matplotlib " + matplotlib.__version__ + "). Don't edit by hand. */",
    "",
    "export type Palette = { id: string; family: string; colors: string[] };",
    "",
    "export const MATPLOTLIB: Palette[] = [",
]
for family, specs in FAMILIES:
    for spec in specs:
        name = spec if isinstance(spec, str) else spec[0]
        lines.append(f'  {{ id: "{name}", family: "{family}", colors: [{", ".join(repr(c).replace(chr(39), chr(34)) for c in colours(spec))}] }},')
lines += ["];", ""]
out = Path(__file__).resolve().parents[1] / "src" / "model" / "palettes.ts"
out.write_text("\n".join(lines))
print(f"wrote {out} ({sum(len(s) for _, s in FAMILIES)} palettes)")
